using Mono.Cecil;
using Mono.Cecil.Cil;
using WhatDidYouSay;
int checks = 0;
void Check(bool ok, string name) { if (!ok) throw new Exception(name); checks++; Console.WriteLine("PASS " + name); }
Check(GainMath.FromPercent(2000) == 21f, "+2000% produces 21x gain");
Check(GainMath.FromPercent(0) == 1f && GainMath.FromPercent(100) == 2f, "zero and +100% mapping");
Check(GainMath.FromPercent(-100) == 1f && GainMath.FromPercent(3000) == 21f, "gain bounds");
Check(GainMath.FromPercent(float.NaN) == 1f && GainMath.FromPercent(float.PositiveInfinity) == 1f, "invalid gain falls back to normal");
float[] wave = [0f, .01f, -.01f, .1f];
GainMath.Apply(wave, 21f);
Check(wave[0] == 0 && Math.Abs(wave[1] - .21f) < .00001f && Math.Abs(wave[2] + .21f) < .00001f && Math.Abs(wave[3] - 2.1f) < .00001f, "sample boost preserves sign and silence without capping at unity");
float[] original = [0f, .125f, -.25f]; float[] copy = (float[])original.Clone();
GainMath.Apply(copy, GainMath.Select(SoundKind.Normal,21,21,21));
Check(copy.SequenceEqual(original), "unselected audio stays bit-identical");
Check(GainMath.Select(SoundKind.Gunshot,2,3,4)==2 && GainMath.Select(SoundKind.Grenade,2,3,4)==3 && GainMath.Select(SoundKind.Plane,2,3,4)==4, "three categories select their own slider");
Check(GainMath.Select((SoundKind)99,21,21,21)==1, "unknown category bypasses boost");
GainMath.Apply([],21); Check(true, "empty audio buffers supported");
using var game = AssemblyDefinition.ReadAssembly(@"C:\SPT\EscapeFromTarkov_Data\Managed\Assembly-CSharp.dll");
var source = game.MainModule.GetType("BetterSource");
Check(source.Methods.Any(m=>m.Name=="SetActive" && m.Parameters.Count==1 && m.Parameters[0].Name=="active" && m.Parameters[0].ParameterType.FullName=="System.Boolean"), "installed game has exact source activation hook");
Check(source.Methods.Any(m=>m.Name=="Release" && m.Parameters.Count==0), "installed game has source release hook");
var plane = game.MainModule.GetType("EFT.Airdrop.ClientAirPlane");
Check(plane.Methods.Count(m=>m.Name=="PlaySound")==1 && plane.Properties.Any(p=>p.Name=="SoundSource"), "installed game has exact plane playback hook and source getter");
var audio = game.MainModule.GetType("BetterAudio");
Check(audio.Fields.Any(f=>f.Name=="SourceGroups") && source.Fields.Any(f=>f.Name=="ReleaseListener"), "audio pool identity members exist");
var group=audio.NestedTypes.Single(t=>t.Name=="AudioSourceGroupType");
Check((int)group.Fields.Single(f=>f.Name=="Gunshots").Constant==0 && (int)group.Fields.Single(f=>f.Name=="Grenades").Constant==11, "target audio categories match installed game");
var mixer=audio.NestedTypes.Single(t=>t.Name=="NonspatialAudioMixer`1");
var borrow=mixer.Methods.Single(m=>m.Name=="BorrowSource");
var il=borrow.Body.Instructions;
int listener=il.ToList().FindIndex(i=>i.OpCode==OpCodes.Stfld && i.Operand is FieldReference f && f.Name=="ReleaseListener");
int activate=il.ToList().FindIndex(i=>i.Operand is MethodReference m && m.Name=="SetActive");
Check(listener>=0 && activate>listener,"pool assigns category identity before activation hook");
var output=Path.GetFullPath(Path.Combine(AppContext.BaseDirectory,"../../../../../Client/bin/Release/net472/zezinho.WhatDidYouSay.dll"));
using var mod=AssemblyDefinition.ReadAssembly(output);
var filter=mod.MainModule.GetType("WhatDidYouSay.MemeGain").Methods.Single(m=>m.Name=="OnAudioFilterRead");
Check(!filter.Body.Instructions.Any(i=>i.Operand is MethodReference m && (m.DeclaringType.Namespace.StartsWith("UnityEngine") || m.DeclaringType.Namespace.StartsWith("BepInEx"))),"audio callback never calls Unity or configuration APIs");
Console.WriteLine($"{checks} checks passed");
